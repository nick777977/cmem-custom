import { afterAll, describe, expect, it } from 'bun:test';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync } from 'node:fs';
import path from 'node:path';
import { deadlines, leafCases, refusalCases, prepareCopiedBundle, runCase, syntheticEnvironment } from '../../scripts/enterprise-local/compiled-smoke.mjs';

const workspace = process.cwd();
const task = path.resolve('.scratch/enterprise-local/windows-09b');
mkdirSync(task, { recursive: true });
const root = mkdtempSync(path.join(task, 'orchestration-'));
afterAll(() => {
  const delta = path.relative(realpathSync(task), realpathSync(root));
  if (!delta || path.isAbsolute(delta) || delta === '..' || delta.startsWith(`..${path.sep}`)) throw new Error('unsafe test cleanup');
  rmSync(root, { recursive: true });
});
// Tool strings are synthetic: no tool is executed or discovered in these tests.
const tools = { node: path.join(root, 'tools', 'node.exe'), bun: path.join(root, 'tools', 'bun.exe') };
const names = ['claude-mem-launcher.cjs', 'ensure-launcher.cjs', 'worker-service.cjs'];
const hashes = Object.fromEntries(names.map(name => [name, createHash('sha256').update(readFileSync(path.join(workspace, 'plugin', 'scripts', name))).digest('hex')]));
function fixture(name: string) { return prepareCopiedBundle({ workspace, sandbox: path.join(root, name), hashes, tools }); }
function mockProcess(output: object | Promise<object>, cleanupFails = false) {
  const events: string[] = [];
  return { events, adapter: { kind: 'mock', launch(spec: any) {
    events.push(`launch:${spec.id}`);
    return {
      completion: Promise.resolve(output),
      stopOwnedTree() { events.push('stop-owned-tree'); if (cleanupFails) throw new Error('cleanup failed'); },
      assertReleased() { events.push('assert-released'); },
    };
  } } };
}
describe('compiled-entrypoint orchestration (MOCK ONLY, V1)', () => {
  it('builds an env allowlist with no ambient auth/model/profile inheritance', () => {
    const env = syntheticEnvironment(root, tools);
    expect(env.CODEX_HOME).toBe(path.join(root, 'codex'));
    expect(env.PATH).toBe(path.dirname(tools.node));
    for (const name of ['AWS_PROFILE', 'ANTHROPIC_API_KEY', 'OPENAI_API_KEY', 'NODE_OPTIONS', 'CLAUDE_PLUGIN_ROOT', 'PLUGIN_ROOT']) expect(name in env).toBe(false);
    expect(env.BUN_INSTALL_AUTO).toBe('disable');
  });
  it('copies exact generated bytes into spaces/Unicode, never imports/executes them', () => {
    const f = fixture('копія bundle');
    expect(readFileSync(path.join(f.bundle, 'scripts', names[0]))).toEqual(readFileSync(path.join(workspace, 'plugin', 'scripts', names[0])));
    expect(existsSync(path.join(f.sandbox, 'node_modules'))).toBe(true);
    expect(leafCases(f, 1).map((item: any) => item.evidence)).toEqual(['load-only', 'controlled-refusal', 'no-op']);
    expect(() => fixture('копія bundle')).toThrow(); // Never reuse state.
  });
  it('fails on wrong source hashes and outside scratch before launch', () => {
    expect(() => prepareCopiedBundle({ workspace, sandbox: path.join(root, 'bad-hash'), hashes: {}, tools })).toThrow('ARTIFACT_HASH_MISMATCH');
    expect(() => prepareCopiedBundle({ workspace, sandbox: workspace, hashes, tools })).toThrow('OUTSIDE_OWNED_SANDBOX');
  });
  it('requires an explicit process boundary (no native/default adapter)', async () => {
    await expect(runCase({}, undefined)).rejects.toThrow('APPROVED_PROCESS_ADAPTER_REQUIRED');
  });
  it('runs copied entrypoint specs through mocks and always releases ownership', async () => {
    for (const spec of leafCases(fixture('mock-success'), 1)) {
      const output = spec.expected.systemMessageCode
        ? { exit: 0, stdout: JSON.stringify({ systemMessage: 'cmem-light: PRIVATE_LAUNCH_POLICY_PENDING: synthetic' }) + '\n', stderr: 'PRIVATE_LAUNCH_POLICY_PENDING: synthetic\n' }
        : { exit: 0, stdout: spec.expected.stdout, stderr: spec.expected.stderr };
      const mock = mockProcess(output);
      expect(await runCase(spec, mock.adapter)).toMatchObject({ status: 'PASS', level: 'V1', substituted: true, readiness: false });
      expect(mock.events).toEqual([`launch:${spec.id}`, 'stop-owned-tree', 'assert-released']);
    }
  });
  it('rejects async boot failure, malformed JSON, missing refusal and oversized output', async () => {
    const spec = leafCases(fixture('bad-output'), 1)[1];
    for (const output of [
      { exit: 1, stdout: '', stderr: 'import error' },
      { exit: 0, stdout: 'not-json', stderr: '' },
      { exit: 0, stdout: '{}', stderr: '' },
      { exit: 0, stdout: 'x'.repeat(deadlines.maxOutputBytes + 1), stderr: '' },
    ]) {
      const mock = mockProcess(output);
      await expect(runCase(spec, mock.adapter)).rejects.toThrow();
      expect(mock.events.slice(-2)).toEqual(['stop-owned-tree', 'assert-released']);
    }
  });
  it('enforces deadlines and fails cleanup instead of reporting PASS', async () => {
    const spec = { ...leafCases(fixture('timeout'), 1)[0], runMs: 5 };
    const mock = mockProcess(new Promise(() => {}));
    await expect(runCase(spec, mock.adapter)).rejects.toThrow('PROCESS_DEADLINE');
    expect(mock.events.slice(-2)).toEqual(['stop-owned-tree', 'assert-released']);
    const failed = mockProcess({ exit: 0, stdout: '1\n', stderr: '' }, true);
    await expect(runCase(spec, failed.adapter)).rejects.toThrow('cleanup failed');
  });
  it('releases ownership after asynchronous process rejection and bounds stuck cleanup', async () => {
    const spec = { ...leafCases(fixture('async-failure'), 1)[0], cleanupMs: 5 };
    const rejected = mockProcess(Promise.reject(new Error('async import failure')));
    await expect(runCase(spec, rejected.adapter)).rejects.toThrow('async import failure');
    expect(rejected.events.slice(-2)).toEqual(['stop-owned-tree', 'assert-released']);
    const stuck = { kind: 'mock', launch: () => ({
      completion: Promise.resolve({ exit: 0, stdout: '1\n', stderr: '' }),
      stopOwnedTree: () => new Promise(() => {}), assertReleased() { throw new Error('still owned'); },
    }) };
    await expect(runCase(spec, stuck)).rejects.toThrow('CLEANUP_DEADLINE');
  });
  it('defines missing/stale/unapproved specs against actual copied launcher paths (mocks only)', async () => {
    const f = fixture('refusal specs');
    const specs = refusalCases(f);
    expect(specs.map((s: any) => s.expected.stderrCode)).toEqual(['LOCAL_BUNDLE_ROOT_REQUIRED', 'LOCAL_BUNDLE_MISSING', 'LOCAL_BUNDLE_STALE', 'PRIVATE_LAUNCH_POLICY_PENDING']);
    for (const spec of specs) {
      expect(spec.args[0]).toBe(path.join(f.bundle, 'scripts', names[0]));
      const output = { exit: 1, stdout: '', stderr: `cmem-light: ${spec.expected.stderrCode}: synthetic refusal\n` };
      const mock = mockProcess(output);
      expect(await runCase(spec, mock.adapter)).toMatchObject({ level: 'V1', substituted: true, readiness: false });
      expect(mock.events.slice(-2)).toEqual(['stop-owned-tree', 'assert-released']);
      await expect(runCase(spec, mockProcess({ ...output, exit: 0 }).adapter)).rejects.toThrow('UNEXPECTED_PROCESS_EXIT');
      await expect(runCase(spec, mockProcess({ ...output, stderr: 'different failure' }).adapter)).rejects.toThrow('MISSING_CONTROLLED_REFUSAL');
    }
  });
});
